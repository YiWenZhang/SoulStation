def get_score_level(score):
    """
    根据 SCL-90 因子分 (1-5) 匹配到 1-5 的等级
    映射逻辑：
    < 1.5 -> 1 (无)
    < 2.5 -> 2 (轻微)
    < 3.5 -> 3 (有点)
    < 4.5 -> 4 (中等)
    >= 4.5 -> 5 (严重)
    """
    if score < 1.5:
        return 1
    elif score < 2.5:
        return 2
    elif score < 3.5:
        return 3
    elif score < 4.5:
        return 4
    else:
        return 5


def generate_report_markdown(radar_data, risk_level, high_risk_dims):
    """
    生成详细的 Markdown 报告文本
    :param radar_data: 字典 {"维度名": 分数, ...}
    :param risk_level: 字符串 'good', 'mild', 'moderate', 'severe'
    :param high_risk_dims: 列表 ["维度名", ...]
    :return: markdown string
    """
    # 1. 整体状态总结
    summary_text = "### 1. 整体状态总结\n\n"
    if risk_level == 'good':
        summary_text += "您的心理状态整体良好。各维度评分均在正常范围内，显示出您拥有较好的心理调节能力和适应能力。请继续保持当前的生活方式，注重劳逸结合。"
    elif risk_level == 'mild':
        summary_text += "您的心理状态存在轻微波动。虽然大部分维度正常，但在部分领域表现出了些许压力迹象。这通常是近期生活事件引起的暂时性反应，通过自我调节通常可以缓解。"
    elif risk_level == 'moderate':
        summary_text += "您目前的心理状态主要表现为**中度风险**。数据显示您在某些维度上承受了较为明显的困扰，可能已经影响到了日常生活的质量。建议您重视这些信号，并尝试积极干预。"
    elif risk_level == 'severe':
        summary_text += "您目前的心理状态**风险较高**。多个核心维度的评分显著超出常模，表明您可能正处于一段较为艰难的时期。这并非软弱的表现，而是身心发出的求助信号，建议及时寻求专业帮助。"
    else:
        summary_text += "您的心理状态存在轻微波动。虽然大部分维度正常，但在部分领域表现出了些许压力迹象。"

    # 2. 维度详细解读 (动态匹配文档内容)
    advice_text = "\n\n### 2. 维度详细解读\n\n"

    # 策略：优先展示高风险维度，如果没有高风险，展示得分最高的两个维度
    targets = high_risk_dims if high_risk_dims else []
    if not targets:
        # 按分数降序排列
        sorted_dims = sorted(radar_data.items(), key=lambda x: x[1], reverse=True)
        # 取前2个
        targets = [d[0] for d in sorted_dims[:2]]

    if not targets:
        advice_text += "各项指标均平稳，无需要特别关注的维度。\n"
    else:
        for dim in targets:
            score = radar_data.get(dim, 1)
            level = get_score_level(score)

            # 容错处理：如果维度名不完全匹配（比如前端叫'睡眠'），尝试匹配 '其他'
            rule_key = dim
            if dim not in SCL90_RULES and dim in ["睡眠", "饮食"]:
                rule_key = "其他"

            content_map = SCL90_RULES.get(rule_key, {})
            # 获取对应的解释文本，默认取 level 2
            interpretation = content_map.get(level, content_map.get(2, "暂无详细解释"))

            advice_text += f"**【{dim}】 (评分 {score:.1f})**\n* {interpretation}\n\n"

    # 3. 通用调节与专业指引
    general_text = """### 3. 通用调节方法
* **正念冥想**：每天坚持10分钟的正念练习，帮助大脑从纷乱的思绪中抽离。
* **规律运动**：有氧运动能促进多巴胺分泌，是天然的抗焦虑药物。
* **社会支持**：与信任的朋友或家人倾诉，不要独自承担所有压力。

### 4. 专业支持指引
如果您感到无法独自应对当前的情绪，或者这些症状已经严重影响了睡眠和工作，**请务必寻求专业帮助**。您可以点击下方的“发起深度问诊”按钮，与AI心理顾问进行初步沟通，或前往正规医疗机构就诊。
"""

    return summary_text + advice_text + general_text